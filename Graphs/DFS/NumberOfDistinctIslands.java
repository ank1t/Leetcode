import java.util.*;

//https://leetcode.com/problems/number-of-distinct-islands/description/
class Solution {
    int m, n;

    public int numDistinctIslands(int[][] grid) {
        m = grid.length;
        n = grid[0].length;
        Queue<RowColPair> q = new LinkedList<>();
        boolean[] visited = new boolean[m * n];
        int[][] directions = {{1,0},{-1,0},{0,1},{0,-1}};
        HashSet<String> islands = new HashSet<>();

        for(int i = 0;i < m;i++) {
            for(int j = 0;j < n;j++) {
                if(grid[i][j] == 1 && !visited[i * n + j]) {
                    q.add(new RowColPair(i, j, 0));
                    visited[i * n + j] = true;
                    String traversalDirection = "X";

                    while(!q.isEmpty()) {
                        RowColPair pair = q.poll();

                        for(int[] direction: directions) {
                            int newRow = direction[0] + pair.row;
                            int newCol = direction[1] + pair.col;

                            if(isValid(newRow, newCol, grid) && !visited[newRow * n + newCol]) {
                                q.add(new RowColPair(newRow, newCol, pair.id + 1));
                                visited[newRow * n + newCol] = true;
                                traversalDirection += pair.id + getDirection(direction);
                            }
                        }
                    }
                    islands.add(traversalDirection);
                }
            }
        }

        return islands.size();
    }

    boolean isValid(int row, int col, int[][] grid) {
        return row >= 0 && row < m && col >= 0 && col < n && grid[row][col] == 1;
    }

    String getDirection(int[] direction) {
        if(direction[0] == 1 && direction[1] == 0) return "D";
        else if(direction[0] == -1 && direction[1] == 0) return "U";
        else if(direction[0] == 0 && direction[1] == 1) return "R";
        else return "L";
    }
}

class Solution1 {
    private int[][] grid;
    private boolean[][] visited;
    private StringBuffer currentIsland;

    public int numDistinctIslands(int[][] grid) {
        this.grid = grid;
        this.visited = new boolean[grid.length][grid[0].length];
        Set<String> islands = new HashSet<>();
        for (int row = 0; row < grid.length; row++) {
            for (int col = 0; col < grid[0].length; col++) {
                currentIsland = new StringBuffer();
                dfs(row, col, '0');
                if (currentIsland.length() == 0) {
                    continue;
                }
                islands.add(currentIsland.toString());
            }
        }
        return islands.size();
    }

    private void dfs(int row, int col, char dir) {
        if (row < 0 || col < 0 || row >= grid.length || col >= grid[0].length) {
            return;
        }
        if (visited[row][col] || grid[row][col] == 0) {
            return;
        }
        visited[row][col] = true;
        currentIsland.append(dir);
        dfs(row + 1, col, 'D');
        dfs(row - 1, col, 'U');
        dfs(row, col + 1, 'R');
        dfs(row, col - 1, 'L');
        currentIsland.append('0');
    }
}
class RowColPair {
    int row;
    int col;
    int id;

    RowColPair(int row, int col, int id) {
        this.row = row;
        this.col = col;
        this.id = id;
    }
}

